# -*- coding: utf-8 -*-
"""A schedule change must never rewrite the past.

Reproduces what happened to Raziya (S074): she delivered Mon/Wed/Fri through
mid-August, moved to Mon/Tue/Thu around the 25th, and the app promptly showed
three unmarked "past orders" on Tuesdays and Thursdays in the second week of
August — days she had never been due. They were generated by the backfill reading
TODAY'S plan over history.

Worse than confusing: planned rows count against the pack, so three invented
orders silently shorten a 20-meal pack to 17.

    python test_schedule_history.py
"""
import os
import sqlite3
import sys
import tempfile
from datetime import date

APP_DIR = os.path.dirname(os.path.abspath(__file__))
LIVE_DB = os.path.join(APP_DIR, "oggainz.db")

# An empty throwaway database, built by the app's own schema. Never the live one.
_tmp = os.path.join(tempfile.gettempdir(), "oggainz_schedhist.db")
for _s in ("", "-wal", "-shm"):
    try:
        os.remove(_tmp + _s)
    except OSError:
        pass
os.environ["OG_DB_PATH"] = _tmp
os.environ.setdefault("OG_SECRET_KEY", "test-secret")

sys.path.insert(0, APP_DIR)
import db      # noqa: E402
import core    # noqa: E402

if os.path.abspath(db.DB_PATH) == os.path.abspath(LIVE_DB):
    raise SystemExit("refusing to run against the live database")

FAILS = []


def check(name, cond, detail=""):
    print(("  ok   " if cond else "  FAIL ") + name + (("  — " + detail) if detail else ""))
    if not cond:
        FAILS.append(name)


def iso(d):
    return d.strftime("%Y-%m-%d")


# A fixed "today" so the test reads the same in any week. Monday.
TODAY = date(2026, 8, 31)
core._today_iso = lambda: iso(TODAY)          # noqa: E305


db.init_db()
conn = sqlite3.connect(_tmp)
conn.row_factory = sqlite3.Row

print("\nschedule history — a change must not rewrite the past")
print("-" * 62)

# Her pack: started Fri 7 Aug, 20 meals, weekly schedule.
START = date(2026, 8, 7)
conn.execute(
    "INSERT INTO subscriptions(id,customer_id,customer_name,plan_name,start_date,"
    "month,total_meals_scheduled,remaining_meals,status,schedule_mode,slot) "
    "VALUES('S074','C1','Raziya','Custom Meal Pack',?,?,20,20,'Active','weekly','Dinner')",
    (iso(START), "Aug-2026"))
conn.commit()

MON, TUE, WED, THU, FRI = 0, 1, 2, 3, 4


def plan(days):
    return [{"weekday": d, "active": 1, "meals": 1} for d in days]


# --- the original schedule, in force from the start ---------------------------
core.save_day_plan(conn, "S074", plan([MON, WED, FRI]))

CHANGE_DAY = date(2026, 8, 25)          # the Monday she moved to Mon/Tue/Thu

print("\n before the change, the old plan is what applies")
check("Wed 12 Aug was a delivery day",
      core.plan_for_day(conn, conn.execute("SELECT * FROM subscriptions WHERE id='S074'")
                        .fetchone(), "2026-08-12")["deliver"])
check("Tue 11 Aug was NOT a delivery day",
      not core.plan_for_day(conn, conn.execute("SELECT * FROM subscriptions WHERE id='S074'")
                            .fetchone(), "2026-08-11")["deliver"])

# --- she actually got fed on Mon/Wed/Fri --------------------------------------
for d in ("2026-08-07", "2026-08-10", "2026-08-12", "2026-08-14",
          "2026-08-17", "2026-08-19"):
    conn.execute(
        "INSERT INTO deliveries(date,subscription_id,customer_id,name,meal_type,"
        "status,month) VALUES(?,'S074','C1','Raziya','Dinner','Delivered','Aug-2026')", (d,))
conn.commit()

# --- the schedule change, filed the way the edit screen now files it ----------
core.save_day_plan(conn, "S074", plan([MON, TUE, THU]),
                   effective_from=iso(CHANGE_DAY))

print("\n after the change, each date is read against the plan of its own week")
sub = conn.execute("SELECT * FROM subscriptions WHERE id='S074'").fetchone()
cases = [
    ("2026-08-11", "Tue", False, "before the change — she was Mon/Wed/Fri then"),
    ("2026-08-13", "Thu", False, "before the change"),
    ("2026-08-18", "Tue", False, "before the change"),
    ("2026-08-12", "Wed", True,  "before the change — Wed was a real day"),
    ("2026-08-19", "Wed", True,  "before the change"),
    ("2026-08-25", "Tue", True,  "on the change day — new plan applies"),
    ("2026-08-27", "Thu", True,  "after the change"),
    ("2026-08-26", "Wed", False, "after the change — Wed is gone now"),
    ("2026-09-01", "Tue", True,  "future"),
]
for iso_d, wd, want, why in cases:
    got = core.plan_for_day(conn, sub, iso_d)["deliver"]
    check("%s %s -> %s (%s)" % (iso_d, wd, "deliver" if want else "no delivery", why),
          got == want, "got deliver=%s" % got)

print("\n the backfill invents nothing in the past")
created = core.backfill_sub_days(conn, "S074")
rows = conn.execute(
    "SELECT date,status FROM deliveries WHERE subscription_id='S074' ORDER BY date"
).fetchall()
phantom = [r["date"] for r in rows
           if r["status"] == "Pending" and r["date"] in
           ("2026-08-11", "2026-08-13", "2026-08-18", "2026-08-20")]
check("no Pending order on a pre-change Tue/Thu", not phantom,
      "invented: %s" % phantom)
check("history untouched — 6 Delivered rows still there",
      len([r for r in rows if r["status"] == "Delivered"]) == 6)

made = [r["date"] for r in rows if r["status"] == "Pending"]
print("       backfill created %d row(s): %s" % (created, made))

# The invariant is NOT "nothing before the change date". A Friday she was due
# under the old Mon/Wed/Fri plan and never got marked is a real unmarked order and
# should surface — that is what the backfill exists for. What must never happen is
# a row on a day she was not due UNDER THE PLAN IN FORCE THAT DAY.
bad = [d for d in made if not core.plan_for_day(conn, sub, d)["deliver"]]
check("every row it created was a real delivery day for its own date",
      not bad, "wrong days: %s" % bad)
old_era = [d for d in made if d < iso(CHANGE_DAY)]
check("pre-change rows follow the OLD Mon/Wed/Fri plan",
      all(date.fromisoformat(d).weekday() in (MON, WED, FRI) for d in old_era),
      str(old_era))
new_era = [d for d in made if d >= iso(CHANGE_DAY)]
check("post-change rows follow the NEW Mon/Tue/Thu plan",
      all(date.fromisoformat(d).weekday() in (MON, TUE, THU) for d in new_era),
      str(new_era))

print("\n the pack is not silently shortened")
used = len([r for r in rows if r["status"] in ("Pending", "Delivered")])
check("planned + delivered stays within the 20 she bought", used <= 20, "used=%d" % used)
check("no meal lost to a phantom", used == 6 + len(made), "used=%d" % used)

print("\n the current plan is still what the screens show")
cur = core.day_plan_for(conn, "S074")
check("summary reads the latest generation",
      sorted(cur) == [MON, TUE, THU], str(sorted(cur)))
check("schedule_summary says Mon, Tue, Thu",
      core.schedule_summary(conn, sub) == "Mon, Tue, Thu",
      core.schedule_summary(conn, sub))

print("\n old packs with no generation stamp behave exactly as before")
conn.execute(
    "INSERT INTO subscriptions(id,customer_id,customer_name,plan_name,start_date,"
    "month,total_meals_scheduled,remaining_meals,status,schedule_mode,slot) "
    "VALUES('S099','C2','Legacy','Custom',?,?,10,10,'Active','weekly','Dinner')",
    (iso(START), "Aug-2026"))
conn.commit()
conn.execute("INSERT INTO subscription_day_plan(subscription_id,weekday,active,meals) "
             "VALUES('S099',?,1,1)", (WED,))
conn.commit()
legacy = conn.execute("SELECT * FROM subscriptions WHERE id='S099'").fetchone()
check("a NULL effective_from still means 'always'",
      core.plan_for_day(conn, legacy, "2026-08-12")["deliver"]
      and not core.plan_for_day(conn, legacy, "2026-08-11")["deliver"])

print("\n re-editing on the same day corrects, it does not stack")
core.save_day_plan(conn, "S074", plan([MON, THU]), effective_from=iso(CHANGE_DAY))
gens = {r["effective_from"] for r in conn.execute(
    "SELECT effective_from FROM subscription_day_plan WHERE subscription_id='S074'")}
check("still just two generations", gens == {None, iso(CHANGE_DAY)}, str(gens))
check("Tue is gone from the current plan",
      sorted(core.day_plan_for(conn, "S074")) == [MON, THU])
check("but Wed 12 Aug is still historically a delivery day",
      core.plan_for_day(conn, sub, "2026-08-12")["deliver"])

print("-" * 62)
if FAILS:
    print("FAILED: %d check(s) -> %s\n" % (len(FAILS), ", ".join(FAILS)))
    sys.exit(1)
print("all checks passed\n")
